/**
 * A complete Unity project for one game: open the folder with Unity Hub ("Add project from disk"
 * or "Import project") and press Play. Built-in render pipeline and the legacy Input Manager, so it
 * needs no packages beyond Unity's own modules. On first open an editor script builds Assets/Scenes/Main.unity,
 * adds it to the build settings and opens it; a runtime bootstrap also starts the game from any empty scene.
 */

const hex = (c: string) => {
  const m = /^#?([0-9a-f]{6})$/i.exec(c.trim());
  const v = m ? parseInt(m[1], 16) : 0x888888;
  return `new Color(${((v >> 16) & 255) / 255}f, ${((v >> 8) & 255) / 255}f, ${(v & 255) / 255}f)`;
};

/**
 * What the browser renderer shows, resolved into data the Unity game can rebuild: preset sky, fog and light,
 * the model file each thing uses (OBJ files exported next to the scripts), every prop, and the HUD.
 */
export type UnityScenePlan = {
  sky?: string; fog?: [number, number]; hemi?: [string, string, number]; sea?: boolean;
  looks: Record<string, { file: string; color?: string; scale: number; box: boolean }>;
  props: Array<{ file: string; x: number; y: number; z: number; height: number; rotate: number }>;
  hud?: { score?: string; timer?: string; scoreLabel?: string; title?: string; message?: string; hearts?: string; heartsMax?: number };
};

const cstr = (v: string) => `"${v.replace(/["\\]/g, "").slice(0, 80)}"`;

function planSource(plan: UnityScenePlan | undefined): string {
  if (!plan) return `    static readonly Dictionary<string, Look> Looks = new Dictionary<string, Look>();
    static readonly PropSpec[] Props = new PropSpec[0];
    static readonly string HudScore = "top-left", HudTimer = "hidden", HudLabel = "Score", HudTitle = "", HudMessage = "";
    static readonly bool Sea = false;
    static readonly Color Hemi1 = new Color(0.55f, 0.6f, 0.75f), Hemi2 = new Color(0.12f, 0.08f, 0.08f);
    const float HemiK = 1f, FogNear = 26f, FogFar = 70f;`;
  const looks = Object.entries(plan.looks).map(([k, l]) => `        { ${cstr(k)}, new Look(${cstr(l.file)}, ${l.color ? `true, ${hex(l.color)}` : "false, Color.white"}, ${l.scale.toFixed(3)}f, ${l.box ? "true" : "false"}) },`).join("\n");
  const props = plan.props.slice(0, 120).map((p) => `        new PropSpec(${cstr(p.file)}, ${p.x}, ${p.y}, ${p.z}, ${p.height.toFixed(3)}f, ${p.rotate.toFixed(1)}f),`).join("\n");
  const h = plan.hud ?? {};
  return `    static readonly Dictionary<string, Look> Looks = new Dictionary<string, Look>
    {
${looks}
    };
    static readonly PropSpec[] Props =
    {
${props}
    };
    static readonly string HudScore = ${cstr(h.score ?? "top-left")}, HudTimer = ${cstr(h.timer ?? "hidden")}, HudLabel = ${cstr(h.scoreLabel ?? "Score")}, HudTitle = ${cstr(h.title ?? "")}, HudMessage = ${cstr(h.message ?? "")}, HudHearts = ${cstr(h.hearts ?? "")};
    static readonly int HudHeartsMax = ${Math.max(1, Math.min(10, Math.trunc(h.heartsMax ?? 5)))};
    static readonly bool Sea = ${plan.sea === false ? "false" : "true"};
    static readonly Color Hemi1 = ${hex(plan.hemi?.[0] ?? "#9aa6c8")}, Hemi2 = ${hex(plan.hemi?.[1] ?? "#1a0f10")};
    const float HemiK = ${(plan.hemi?.[2] ?? 0.95).toFixed(2)}f, FogNear = ${(plan.fog?.[0] ?? 26).toFixed(1)}f, FogFar = ${(plan.fog?.[1] ?? 70).toFixed(1)}f;`;
}

export function gameSource(className: string, opts: { seed: number; view: "2d" | "3d"; sky: string; ground: string; accent: string; title: string; prefabs: Record<string, PrefabDef>; plan?: UnityScenePlan }): string {
  const all = { ...BUILTIN_PREFABS, ...opts.prefabs };
  const colors = Object.entries(all).map(([k, p]) => `        { "${k.replace(/[^A-Za-z0-9_-]/g, "")}", ${hex(p.color ?? "#9aa4b2")} },`).join("\n");
  return `// ForkLabGame.cs - generated by ForkLab. The whole game: simulation, camera, lights, models, score and restart.
using System.Collections.Generic;
using UnityEngine;
using ForkLab;

public class ForkLabGame : MonoBehaviour
{
    public string title = "${opts.title.replace(/["\\]/g, "")}";
    public uint seed = ${opts.seed};
    [Tooltip("2D is a side-on camera, 3D a third-person camera")]
    public bool sideView = ${opts.view === "2d" ? "true" : "false"};
    public Color sky = ${hex(opts.plan?.sky ?? opts.sky)};
    public Color ground = ${hex(opts.ground)};
    public Color accent = ${hex(opts.accent)};

    const float S = 1f / 1000f; // engine milli-units to Unity metres
    static readonly KeyCode[] Keys = { KeyCode.Space, KeyCode.LeftArrow, KeyCode.RightArrow, KeyCode.UpArrow, KeyCode.DownArrow, KeyCode.A, KeyCode.D, KeyCode.W, KeyCode.S };
    static readonly Dictionary<string, Color> PrefabColors = new Dictionary<string, Color>
    {
${colors}
    };

    struct Look { public string file; public bool tint; public Color color; public float scale; public bool box; public Look(string f, bool t, Color c, float s, bool b) { file = f; tint = t; color = c; scale = s; box = b; } }
    struct PropSpec { public string file; public int x, y, z; public float height, rotate; public PropSpec(string f, int x, int y, int z, float h, float r) { file = f; this.x = x; this.y = y; this.z = z; height = h; rotate = r; } }
${planSource(opts.plan)}

    Sim sim;
    Camera cam;
    uint latched; // keys pressed since the last tick, so a quick tap between ticks still counts
    readonly Dictionary<int, Look> entityLooks = new Dictionary<int, Look>();
    readonly Dictionary<int, Vector3> aspects = new Dictionary<int, Vector3>();
    Transform world;
    readonly Dictionary<int, Transform> views = new Dictionary<int, Transform>();
    readonly Dictionary<int, Vector3> prev = new Dictionary<int, Vector3>();
    readonly Dictionary<int, Vector3> curr = new Dictionary<int, Vector3>();
    readonly Dictionary<string, Material> mats = new Dictionary<string, Material>();
    Vector3 camFocus;
    float shake;
    GUIStyle big, small;

    void Start()
    {
        Application.targetFrameRate = 120;
        Time.fixedDeltaTime = 1f / 60f;
        BuildStage();
        Restart();
    }

    void BuildStage()
    {
        cam = Camera.main;
        if (cam == null) { var c = new GameObject("Main Camera"); c.tag = "MainCamera"; cam = c.AddComponent<Camera>(); c.AddComponent<AudioListener>(); }
        cam.clearFlags = CameraClearFlags.SolidColor;
        cam.backgroundColor = sky;
        cam.fieldOfView = 50f;
        cam.orthographic = sideView;
        cam.nearClipPlane = 0.1f; cam.farClipPlane = 300f;
        RenderSettings.ambientMode = UnityEngine.Rendering.AmbientMode.Trilight;
        RenderSettings.ambientSkyColor = Hemi1 * HemiK;
        RenderSettings.ambientEquatorColor = Color.Lerp(Hemi1, Hemi2, 0.5f) * HemiK;
        RenderSettings.ambientGroundColor = Hemi2 * HemiK;
        RenderSettings.fog = true; RenderSettings.fogColor = sky; RenderSettings.fogMode = FogMode.Linear;
        RenderSettings.fogStartDistance = sideView ? 40f : FogNear; RenderSettings.fogEndDistance = sideView ? 90f : FogFar;
        if (FindAny<Light>() == null)
        {
            var l = new GameObject("Moonlight").AddComponent<Light>();
            l.type = LightType.Directional; l.color = new Color(0.9f, 0.93f, 1f); l.intensity = 1.1f; l.shadows = LightShadows.Soft;
            l.transform.rotation = Quaternion.Euler(50f, 30f, 0f);
        }
        world = new GameObject("World").transform;
        world.SetParent(transform, false);
        float ww = Sim.WorldW * S, wd = Sim.WorldD * S;
        var floor = Make(PrimitiveType.Cube, "Floor", ground, 0.15f);
        floor.localScale = new Vector3(ww + 1.2f, 0.5f, wd + 1.2f);
        floor.localPosition = new Vector3(ww / 2f, -0.25f, -wd / 2f);
        camFocus = new Vector3(ww / 2f, 1f, -wd * 0.55f);
        if (Sea) { var sea = Make(PrimitiveType.Cube, "Sea", new Color(0.05f, 0.08f, 0.14f), 0.85f); sea.localScale = new Vector3(160f, 0.1f, 100f); sea.localPosition = new Vector3(ww / 2f, -1.4f, -wd / 2f); }
        // props, at the same places and sizes as in the browser
        foreach (var p in Props)
        {
            Vector3 a;
            var t = Model(p.file, false, Color.white, out a);
            if (t == null) continue;
            float k = p.height / Mathf.Max(a.y, 0.001f);
            t.localScale = Vector3.one * k;
            t.localPosition = new Vector3(p.x * S, p.y * S + a.y * k / 2f, -p.z * S);
            t.localRotation = Quaternion.Euler(0f, -p.rotate, 0f);
        }
    }

    static T FindAny<T>() where T : Object
    {
#if UNITY_2023_1_OR_NEWER
        return Object.FindFirstObjectByType<T>();
#else
        return Object.FindObjectOfType<T>();
#endif
    }

    Transform Make(PrimitiveType type, string name, Color color, float gloss)
    {
        var go = GameObject.CreatePrimitive(type);
        go.name = name;
        var col = go.GetComponent<Collider>();
        if (col != null) Destroy(col);
        go.GetComponent<Renderer>().sharedMaterial = Mat(color, gloss);
        go.transform.SetParent(world, false);
        return go.transform;
    }

    /// A model from Resources/ForkLabModels, fitted inside a unit box centred on its holder. Null if missing.
    Transform Model(string file, bool tint, Color color, out Vector3 aspect)
    {
        aspect = Vector3.one;
        var prefab = Resources.Load<GameObject>("ForkLabModels/" + file);
        if (prefab == null) return null;
        var holder = new GameObject(file).transform;
        holder.SetParent(world, false);
        var go = Instantiate(prefab);
        foreach (var c in go.GetComponentsInChildren<Collider>()) Destroy(c);
        var rs = go.GetComponentsInChildren<Renderer>();
        if (rs.Length == 0) { go.transform.SetParent(holder, false); return holder; }
        Bounds b = rs[0].bounds;
        foreach (var r in rs) b.Encapsulate(r.bounds);
        float m = Mathf.Max(b.size.x, Mathf.Max(b.size.y, Mathf.Max(b.size.z, 0.0001f)));
        go.transform.localScale = go.transform.localScale / m;
        go.transform.position = (go.transform.position - b.center) / m;
        go.transform.SetParent(holder, false);
        aspect = b.size / m;
        if (tint) foreach (var r in rs) foreach (var mat in r.materials) mat.color = color;
        return holder;
    }

    Material Mat(Color c, float gloss)
    {
        string key = ColorUtility.ToHtmlStringRGB(c) + gloss;
        Material m;
        if (mats.TryGetValue(key, out m)) return m;
        var shader = Shader.Find("Standard");
        if (shader == null) shader = Shader.Find("Universal Render Pipeline/Lit");
        m = new Material(shader);
        m.color = c;
        if (m.HasProperty("_Glossiness")) m.SetFloat("_Glossiness", gloss);
        mats[key] = m;
        return m;
    }

    Transform ViewFor(Entity e)
    {
        Look look;
        if (Looks.TryGetValue(e.PrefabName, out look) || Looks.TryGetValue(e.Tag, out look))
        {
            Vector3 a;
            var t = Model(look.file, look.tint, look.color, out a);
            if (t != null) { entityLooks[e.Id] = look; aspects[e.Id] = a; return t; }
        }
        Color c;
        if (!PrefabColors.TryGetValue(e.PrefabName, out c)) c = new Color(0.6f, 0.64f, 0.7f);
        switch (e.Tag)
        {
            case "player": return Make(PrimitiveType.Capsule, "Player", accent, 0.4f);
            case "coin": return Make(PrimitiveType.Cylinder, "Coin", new Color(0.95f, 0.8f, 0.4f), 0.8f);
            case "rock": return Make(PrimitiveType.Sphere, "Rock", c, 0.1f);
            case "bolt": return Make(PrimitiveType.Sphere, "Bolt", new Color(0.4f, 0.85f, 1f), 0.9f);
            case "sacred": return Make(PrimitiveType.Sphere, "Sacred", c, 0.7f);
            case "wall": return Make(e.PrefabName == "pillar" ? PrimitiveType.Cylinder : PrimitiveType.Cube, "Wall", c, 0.2f);
            default: return Make(PrimitiveType.Cube, e.Tag, c, 0.25f);
        }
    }

    public void Restart()
    {
        foreach (var kv in views) Destroy(kv.Value.gameObject);
        views.Clear(); prev.Clear(); curr.Clear(); entityLooks.Clear(); aspects.Clear();
        sim = new Sim(seed, new ${className}());
        shake = 0f;
    }

    // engine (x right, y up, z toward the camera) to Unity (x right, y up, z away from the camera): z is negated.
    // In 2D every entity sits on one plane at the default depth, matching the browser.
    Vector3 Centre(Entity e)
    {
        float z = sideView ? -(Sim.DefaultZ * S + 0.5f) : -(e.Z + e.D / 2f) * S;
        return new Vector3((e.X + e.W / 2f) * S, (e.Y + e.H / 2f) * S, z);
    }

    void FixedUpdate()
    {
        if (sim == null || sim.Status != "running") return;
        uint m = latched;
        latched = 0;
        for (int i = 0; i < Keys.Length; i++) if (Input.GetKey(Keys[i])) m |= 1u << i;
        prev.Clear();
        foreach (var kv in curr) prev[kv.Key] = kv.Value;
        sim.StepTick(m);
        curr.Clear();
        foreach (var e in sim.Entities) curr[e.Id] = Centre(e);
        if (sim.Status == "lose") shake = 0.35f;
    }

    void Update()
    {
        if (Input.GetKeyDown(KeyCode.R)) Restart();
        for (int i = 0; i < Keys.Length; i++) if (Input.GetKeyDown(Keys[i])) latched |= 1u << i;
        if (sim == null) return;
        float a = Mathf.Clamp01((Time.time - Time.fixedTime) / Time.fixedDeltaTime);
        var seen = new HashSet<int>();
        Vector3 player = camFocus;
        bool hasPlayer = false;
        foreach (var e in sim.Entities)
        {
            seen.Add(e.Id);
            Transform t;
            if (!views.TryGetValue(e.Id, out t)) { t = ViewFor(e); views[e.Id] = t; }
            Vector3 now = curr.ContainsKey(e.Id) ? curr[e.Id] : Centre(e);
            Vector3 was = prev.ContainsKey(e.Id) ? prev[e.Id] : now;
            Vector3 p = Vector3.Lerp(was, now, a);
            float w = e.W * S, h = e.H * S, d = e.D * S;
            Look lk;
            if (entityLooks.TryGetValue(e.Id, out lk))
            {
                // same fitting as the browser: solid things fill their box, others keep proportions
                Vector3 asp = aspects[e.Id];
                if (lk.box) t.localScale = new Vector3(w / Mathf.Max(asp.x, 0.05f), h / Mathf.Max(asp.y, 0.05f), d / Mathf.Max(asp.z, 0.05f));
                else t.localScale = Vector3.one * Mathf.Min(h / Mathf.Max(asp.y, 0.05f), 1.6f * Mathf.Max(w, d) / Mathf.Max(Mathf.Max(asp.x, asp.z), 0.05f)) * lk.scale;
                t.localPosition = new Vector3(p.x, p.y - h / 2f + asp.y * t.localScale.y / 2f, p.z);
                if (e.Vx != 0 || e.Vz != 0) t.rotation = Quaternion.Slerp(t.rotation, Quaternion.LookRotation(new Vector3(e.Vx, 0f, -e.Vz)), Time.deltaTime * 12f);
                if (e.Tag == "coin") t.Rotate(0f, 140f * Time.deltaTime, 0f, Space.Self);
                if (e.Tag == "player") { player = p; hasPlayer = true; }
                continue;
            }
            if (e.Tag == "player") { t.localScale = new Vector3(w, h / 2f, d); if (e.Vx != 0 || e.Vz != 0) t.rotation = Quaternion.Slerp(t.rotation, Quaternion.LookRotation(new Vector3(e.Vx, 0f, -e.Vz)), Time.deltaTime * 12f); player = p; hasPlayer = true; }
            else if (e.Tag == "coin") { t.localScale = new Vector3(w, 0.08f, w); t.Rotate(90f * Time.deltaTime, 0f, 0f, Space.Self); }
            else if (e.Tag == "wall" && e.PrefabName == "pillar") t.localScale = new Vector3(w, h / 2f, d);
            else t.localScale = new Vector3(w, h, d);
            t.localPosition = p;
        }
        var gone = new List<int>();
        foreach (var kv in views) if (!seen.Contains(kv.Key)) gone.Add(kv.Key);
        foreach (var id in gone) { Destroy(views[id].gameObject); views.Remove(id); }

        float ww = Sim.WorldW * S, wh = Sim.WorldH * S;
        Vector3 jitter = shake > 0f ? (Vector3)(Random.insideUnitCircle * shake * 0.6f) : Vector3.zero;
        shake = Mathf.Max(0f, shake - Time.deltaTime);
        if (sideView)
        {
            float h = Mathf.Max(wh * 1.06f, ww * 1.04f / Mathf.Max(0.3f, cam.aspect));
            float z = -(Sim.DefaultZ * S + 0.5f);
            cam.orthographic = true;
            cam.orthographicSize = h / 2f;
            cam.transform.position = new Vector3(ww / 2f, wh / 2f, z - 30f) + jitter;
            cam.transform.LookAt(new Vector3(ww / 2f, wh / 2f, z));
        }
        else
        {
            float wd = Sim.WorldD * S;
            Vector3 target = hasPlayer ? new Vector3(Mathf.Lerp(ww / 2f, player.x, 0.55f), 1f, Mathf.Lerp(-wd * 0.55f, player.z, 0.45f)) : camFocus;
            camFocus = Vector3.Lerp(camFocus, target, Mathf.Clamp01(Time.deltaTime * 3f));
            cam.transform.position = camFocus + new Vector3(0f, 12f, -15.5f) + jitter;
            cam.transform.LookAt(camFocus);
        }
    }

    void Spot(string where, string text)
    {
        float w = 260, x = 20, y = 16;
        if (where.EndsWith("right")) x = Screen.width - w - 20;
        if (where.EndsWith("center")) x = (Screen.width - w) / 2f;
        if (where.StartsWith("bottom")) y = Screen.height - 46;
        GUI.Label(new Rect(x, y, w, 30), text, new GUIStyle(small) { fontSize = 22, fontStyle = FontStyle.Bold, alignment = where.EndsWith("right") ? TextAnchor.UpperRight : where.EndsWith("center") ? TextAnchor.UpperCenter : TextAnchor.UpperLeft });
    }

    void OnGUI()
    {
        if (sim == null) return;
        if (big == null)
        {
            big = new GUIStyle(GUI.skin.label) { fontSize = 34, alignment = TextAnchor.MiddleCenter, fontStyle = FontStyle.Bold };
            small = new GUIStyle(GUI.skin.label) { fontSize = 18 };
            big.normal.textColor = Color.white; small.normal.textColor = new Color(1f, 0.9f, 0.7f);
        }
        // the HUD from the game's scene: score and timer where the game puts them, plus title and message
        if (HudScore != "hidden") Spot(HudScore, HudLabel + "  " + sim.Score);
        if (HudTimer != "hidden") Spot(HudTimer, (sim.Tick / 60f).ToString("0.0") + " s");
        if (HudTitle.Length > 0) GUI.Label(new Rect(0, 12, Screen.width, 40), HudTitle, new GUIStyle(big) { fontSize = 24 });
        if (HudHearts.Length > 0)
        {
            int left = -1;
            foreach (var kv in sim.Vars) if (kv.Key.EndsWith("." + HudHearts)) { left = kv.Value; break; }
            if (left >= 0)
            {
                var hs = new GUIStyle(big) { fontSize = 30 };
                string row = "";
                for (int i = 0; i < Mathf.Max(HudHeartsMax, left); i++) row += i < left ? "\u2665" : "\u2661";
                hs.normal.textColor = new Color(0.89f, 0.28f, 0.35f);
                GUI.Label(new Rect(0, HudTitle.Length > 0 ? 46 : 12, Screen.width, 40), row, hs);
            }
        }
        if (HudMessage.Length > 0) GUI.Label(new Rect(0, Screen.height - 50, Screen.width, 30), HudMessage, new GUIStyle(small) { alignment = TextAnchor.MiddleCenter });
        if (sim.Status != "running")
        {
            string head = sim.Status == "win" ? "You won" : "Run over";
            GUI.Label(new Rect(0, Screen.height / 2f - 40, Screen.width, 50), head + "  ·  " + sim.Score + " points", big);
            GUI.Label(new Rect(0, Screen.height / 2f + 14, Screen.width, 30), "Press R to play again", new GUIStyle(small) { alignment = TextAnchor.MiddleCenter });
        }
    }
}
`;
}

