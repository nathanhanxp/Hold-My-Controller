/*
 * C# export. Three files:
 *   ForkLabCore.cs       fixed-point world, RNG port, AABB, tick loop. Pure C#, no UnityEngine.
 *   Mechanic_<slug>.cs   generated from the graph: one method per node, same order as interpret.ts.
 *   MechanicBehaviour.cs MonoBehaviour that steps the world in FixedUpdate at 60 Hz.
 * The generated code mirrors the TypeScript interpreter exactly, including the per-phase step cap,
 * so the same inputs and seed produce the same snapshots.
 */

export function slugify(title: string): string {
  const s = title.replace(/[^A-Za-z0-9]+/g, " ").trim().split(" ").filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join("");
  return s || "Mechanic";
}

const cs = (s: string) => JSON.stringify(s); // C# accepts the same escaped string literal for ASCII
const safeId = (id: string) => id.replace(/[^A-Za-z0-9_]/g, "_");

function prefabTable(prefabs: Record<string, PrefabDef>): string {
  const all = { ...BUILTIN_PREFABS, ...prefabs };
  return Object.entries(all)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([name, p]) => `            { ${cs(name)}, new Prefab(${cs(p.tag)}, ${p.w}, ${p.h}, ${p.d ?? p.w}, ${p.vx}, ${p.vy}, ${p.vz ?? 0}, ${p.body ? "true" : "false"}, ${p.solid ? "true" : "false"}) },`)
    .join("\n");
}

export function coreSource(prefabs: Record<string, PrefabDef> = {}): string {
  return `// ForkLabCore.cs - generated by ForkLab. Identical for every mechanic. Pure C#, no UnityEngine reference.
// State is int fixed-point milli-units (1 world unit = 1000). 60 ticks per second.
using System;
using System.Collections.Generic;
using System.Text;

namespace ForkLab
{
    public static class Fixed
    {
        public const int StateLimit = 100000000;
        public static int Clamp(int v) { return v > StateLimit ? StateLimit : (v < -StateLimit ? -StateLimit : v); }
        public static int Clamp(long v) { return v > StateLimit ? StateLimit : (v < -StateLimit ? -StateLimit : (int)v); }
    }

    /// Named seeded streams: xmur3 seeding + sfc32. Port of engine/src/rng.ts.
    public sealed class Rng
    {
        private readonly string prefix;
        private readonly Dictionary<string, Stream> streams = new Dictionary<string, Stream>();
        public Rng(uint seed) { prefix = seed.ToString() + "\\u0000"; }
        public Stream Get(string name)
        {
            Stream s;
            if (streams.TryGetValue(name, out s)) return s;
            s = new Stream(prefix + name);
            streams[name] = s;
            return s;
        }
        public sealed class Stream
        {
            private uint a, b, c, d, h;
            public Stream(string input)
            {
                h = 1779033703u ^ (uint)input.Length;
                for (int i = 0; i < input.Length; i++)
                {
                    h = unchecked((h ^ (uint)input[i]) * 3432918353u);
                    h = (h << 13) | (h >> 19);
                }
                a = Mix(); b = Mix(); c = Mix(); d = Mix();
            }
            private uint Mix()
            {
                h = unchecked((h ^ (h >> 16)) * 2246822507u);
                h = unchecked((h ^ (h >> 13)) * 3266489909u);
                h ^= h >> 16;
                return h;
            }
            public uint NextUint32()
            {
                uint result = unchecked(a + b + d);
                d = unchecked(d + 1);
                a = b ^ (b >> 9);
                b = unchecked(c + (c << 3));
                c = (c << 21) | (c >> 11);
                c = unchecked(c + result);
                return result;
            }
            public int NextInt(int min, int maxExclusive)
            {
                long span = (long)maxExclusive - min;
                if (span <= 0) return min;
                const long range = 4294967296L;
                long limit = range - (range % span);
                long v = NextUint32();
                while (v >= limit) v = NextUint32();
                return (int)(min + (v % span));
            }
        }
    }

    public struct Prefab
    {
        public string Tag; public int W, H, D, Vx, Vy, Vz; public bool Body, Solid;
        public Prefab(string tag, int w, int h, int d, int vx, int vy, int vz, bool body, bool solid) { Tag = tag; W = w; H = h; D = d; Vx = vx; Vy = vy; Vz = vz; Body = body; Solid = solid; }
    }

    public sealed class Entity
    {
        public int Id; public string Tag; public string PrefabName;
        public int X, Y, Z, W, H, D, Vx, Vy, Vz, Fx = 1, Fz;
        public bool Body, Solid, Grounded, Alive = true;
        public string Owner; // tag of the shooter; a shot never collides with its shooter's tag
        public bool Overlaps(Entity o) { return X < o.X + o.W && o.X < X + W && Y < o.Y + o.H && o.Y < Y + H && Z < o.Z + o.D && o.Z < Z + D; }
    }

    public sealed class Ctx { public Entity A, B; public bool InStart; }

    public abstract class GraphProgram
    {
        public string Ns;
        public bool SuppressStartSpawns;
        public Sim S;
        public abstract void RunStart();
        public abstract void RunKeys(uint mask, uint pressed, uint released);
        public abstract void RunTicks(int tick);
        public abstract void RunCollisions();
        protected int Steps { get { return S.Steps; } }
        protected bool Step() { return ++S.Steps <= Sim.MaxStepsPerTick; }
        protected static int Cmp(string op, int a, int b)
        {
            switch (op)
            {
                case "lt": return a < b ? 1 : 0;
                case "le": return a <= b ? 1 : 0;
                case "gt": return a > b ? 1 : 0;
                case "ge": return a >= b ? 1 : 0;
                case "eq": return a == b ? 1 : 0;
                case "ne": return a != b ? 1 : 0;
                case "add": return Fixed.Clamp((long)a + b);
                case "sub": return Fixed.Clamp((long)a - b);
                default: return 0;
            }
        }
    }

    /// Tick order (same as engine/src/interpret.ts): inputs; per program OnStart (tick 0), OnKey, OnTick;
    /// integrate; per program OnCollide; deferred spawns then destroys.
    public sealed class Sim
    {
        public const int WorldW = ${WORLD_W};
        public const int WorldH = ${WORLD_H};
        public const int WorldD = ${WORLD_D};
        public const int DefaultZ = ${DEFAULT_Z};
        public const int Margin = ${OFFSCREEN_MARGIN};
        public const int MaxEntities = ${MAX_ENTITIES};
        public const int MaxStepsPerTick = ${MAX_STEPS_PER_TICK};

        public static readonly Dictionary<string, Prefab> Prefabs = new Dictionary<string, Prefab>
        {
${prefabTable(prefabs)}
        };

        public int Tick, Score, Steps;
        public string Status = "running";
        public readonly List<Entity> Entities = new List<Entity>();
        public readonly SortedDictionary<string, int> Vars = new SortedDictionary<string, int>(StringComparer.Ordinal);
        public readonly Rng Rng;
        public readonly List<GraphProgram> Programs = new List<GraphProgram>();
        private int nextId = 1;
        private uint prevMask;
        private readonly List<KeyValuePair<string, int[]>> spawns = new List<KeyValuePair<string, int[]>>(); // x,y,z[,vx,vy,vz]
        private readonly List<string> spawnOwners = new List<string>();
        private readonly HashSet<int> destroys = new HashSet<int>();

        public Sim(uint seed, params GraphProgram[] programs)
        {
            Rng = new Rng(seed);
            foreach (var p in programs) { p.S = this; Programs.Add(p); }
        }

        public void StepTick(uint mask)
        {
            if (Status != "running") return;
            uint pressed = mask & ~prevMask;
            uint released = prevMask & ~mask;
            foreach (var p in Programs)
            {
                Steps = 0;
                if (Tick == 0) p.RunStart();
                p.RunKeys(mask, pressed, released);
                p.RunTicks(Tick);
            }
            Integrate();
            foreach (var p in Programs) { Steps = 0; p.RunCollisions(); }
            for (int i = 0; i < spawns.Count; i++) SpawnNow(spawns[i].Key, spawns[i].Value, spawnOwners[i]);
            spawns.Clear();
            spawnOwners.Clear();
            if (destroys.Count > 0) { Entities.RemoveAll(e => destroys.Contains(e.Id)); destroys.Clear(); }
            prevMask = mask;
            Tick++;
        }

        public void QueueSpawn(string prefab, int x, int y, int z) { spawns.Add(new KeyValuePair<string, int[]>(prefab, new[] { x, y, z })); spawnOwners.Add(null); }
        public static int ISqrt(long n) { if (n <= 0) return 0; long r = (long)Math.Floor(Math.Sqrt((double)n)); while (r * r > n) r -= 1; while ((r + 1) * (r + 1) <= n) r += 1; return (int)r; }
        /// Toward the nearest player along the ground, length sp (same as aimAt in interpret.ts).
        public void AimAt(Entity e, int sp, out int vx, out int vz)
        {
            long cx = e.X + e.W / 2, cz = e.Z + e.D / 2; long bx = 0, bz = 0, bd = -1;
            foreach (var o in Entities) { if (o.Tag != "player" || o.Id == e.Id) continue; long dx = o.X + o.W / 2 - cx, dz = o.Z + o.D / 2 - cz; long d2 = dx * dx + dz * dz; if (bd < 0 || d2 < bd) { bd = d2; bx = dx; bz = dz; } }
            if (bd <= 0) { vx = 0; vz = sp; return; }
            int len = ISqrt(bd); vx = (int)(bx * sp / len); vz = (int)(bz * sp / len);
        }
        public void QueueSpawnV(string prefab, int x, int y, int z, int vx, int vy, int vz, string owner = null) { spawns.Add(new KeyValuePair<string, int[]>(prefab, new[] { x, y, z, vx, vy, vz })); spawnOwners.Add(owner); }
        public void QueueDestroy(Entity e) { destroys.Add(e.Id); }
        public void End(string status) { if (Status == "running") Status = status; }
        public void AddScore(int n) { Score = unchecked(Score + n); }

        public void SpawnNow(string prefab, int[] v, string owner = null)
        {
            Prefab def;
            if (!Prefabs.TryGetValue(prefab, out def) || Entities.Count >= MaxEntities) return;
            var e = new Entity { Id = nextId++, Tag = def.Tag, PrefabName = prefab, X = Fixed.Clamp(v[0]), Y = Fixed.Clamp(v[1]), Z = Fixed.Clamp(v[2]), W = def.W, H = def.H, D = def.D, Vx = def.Vx, Vy = def.Vy, Vz = def.Vz, Body = def.Body, Solid = def.Solid };
            if (v.Length >= 6) { e.Vx = Fixed.Clamp(v[3]); e.Vy = Fixed.Clamp(v[4]); e.Vz = Fixed.Clamp(v[5]); }
            e.Owner = owner;
            Entities.Add(e);
        }
        public bool TryPrefab(string name, out Prefab def) { return Prefabs.TryGetValue(name, out def); }

        public List<Entity> Select(string name, Ctx c)
        {
            var list = new List<Entity>();
            if (name == "a") { if (c.A != null && c.A.Alive) list.Add(c.A); return list; }
            if (name == "b") { if (c.B != null && c.B.Alive) list.Add(c.B); return list; }
            foreach (var e in Entities) if (e.Alive && e.Tag == name) list.Add(e);
            return list;
        }

        public List<Entity[]> Pairs(string tagA, string tagB)
        {
            var output = new List<Entity[]>();
            foreach (var a in Entities)
            {
                if (!a.Alive || a.Tag != tagA) continue;
                foreach (var b in Entities)
                    if (b.Alive && b.Tag == tagB && a.Id != b.Id && a.Owner != b.Tag && b.Owner != a.Tag && a.Overlaps(b)) output.Add(new[] { a, b });
            }
            return output;
        }

        private void Integrate()
        {
            var solids = Entities.FindAll(e => e.Alive && e.Solid);
            foreach (var e in Entities)
            {
                if (!e.Alive) continue;
                if (e.Vx != 0 || e.Vz != 0) { e.Fx = Math.Sign(e.Vx); e.Fz = Math.Sign(e.Vz); }
                if (!e.Body)
                {
                    e.X = Fixed.Clamp((long)e.X + e.Vx);
                    e.Y = Fixed.Clamp((long)e.Y + e.Vy);
                    e.Z = Fixed.Clamp((long)e.Z + e.Vz);
                    if (e.X + e.W < -Margin || e.X > WorldW + Margin || e.Y + e.H < -Margin || e.Y > WorldH + Margin || e.Z + e.D < -Margin || e.Z > WorldD + Margin) destroys.Add(e.Id);
                    continue;
                }
                e.X = Fixed.Clamp((long)e.X + e.Vx);
                foreach (var s in solids)
                    if (s.Id != e.Id && e.Overlaps(s)) { if (e.Vx > 0) e.X = s.X - e.W; else if (e.Vx < 0) e.X = s.X + s.W; e.Vx = 0; }
                if (e.X < 0) e.X = 0;
                if (e.X > WorldW - e.W) e.X = WorldW - e.W;
                e.Z = Fixed.Clamp((long)e.Z + e.Vz);
                foreach (var s in solids)
                    if (s.Id != e.Id && e.Overlaps(s)) { if (e.Vz > 0) e.Z = s.Z - e.D; else if (e.Vz < 0) e.Z = s.Z + s.D; e.Vz = 0; }
                if (e.Z < 0) e.Z = 0;
                if (e.Z > WorldD - e.D) e.Z = WorldD - e.D;
                e.Y = Fixed.Clamp((long)e.Y + e.Vy);
                e.Grounded = false;
                foreach (var s in solids)
                    if (s.Id != e.Id && e.Overlaps(s)) { if (e.Vy <= 0) { e.Y = s.Y + s.H; e.Grounded = true; } else e.Y = s.Y - e.H; e.Vy = 0; }
                if (e.Y <= 0) { e.Y = 0; if (e.Vy < 0) e.Vy = 0; e.Grounded = true; }
                if (e.Y > WorldH - e.H) { e.Y = WorldH - e.H; if (e.Vy > 0) e.Vy = 0; }
            }
        }

        /// Canonical JSON of the snapshot (keys sorted), byte-identical to engine canonical(snapshot).
        public string SnapshotJson()
        {
            var sb = new StringBuilder();
            sb.Append("{\\"entities\\":[");
            for (int i = 0; i < Entities.Count; i++)
            {
                var e = Entities[i];
                if (i > 0) sb.Append(',');
                sb.Append("{\\"alive\\":").Append(e.Alive ? "true" : "false")
                  .Append(",\\"id\\":").Append(e.Id)
                  .Append(",\\"tag\\":\\"").Append(e.Tag).Append('"')
                  .Append(",\\"vx\\":").Append(e.Vx).Append(",\\"vy\\":").Append(e.Vy).Append(",\\"vz\\":").Append(e.Vz)
                  .Append(",\\"x\\":").Append(e.X).Append(",\\"y\\":").Append(e.Y).Append(",\\"z\\":").Append(e.Z).Append('}');
            }
            sb.Append("],\\"score\\":").Append(Score).Append(",\\"status\\":\\"").Append(Status).Append("\\",\\"tick\\":").Append(Tick).Append(",\\"vars\\":{");
            bool first = true;
            foreach (var kv in Vars)
            {
                if (!first) sb.Append(',');
                first = false;
                sb.Append('"').Append(kv.Key).Append("\\":").Append(kv.Value);
            }
            sb.Append("}}");
            return sb.ToString();
        }
    }
}
`;
}

/** Generate the per-graph program class. */
export function mechanicSource(graph: Graph, hash: string, className = `Mechanic_${slugify(graph.title)}`, ns = "mech"): string {
  const byId = new Map(graph.nodes.map((n) => [n.id, n]));
  const execNext = new Map<string, string[]>();
  const dataIn = new Map<string, string>();
  for (const e of graph.edges) {
    if (!byId.has(e.from.node) || !byId.has(e.to.node)) continue;
    const key = `${e.from.node}\u0000${e.from.port}`;
    if (e.kind === "exec") execNext.set(key, [...(execNext.get(key) ?? []), e.to.node].sort());
    else dataIn.set(`${e.to.node}\u0000${e.to.port}`, e.from.node);
  }
  const sorted = [...graph.nodes].sort((a, b) => (a.id < b.id ? -1 : 1));
  const runOut = (id: string, port: string) => (execNext.get(`${id}\u0000${port}`) ?? []).map((t) => `X_${safeId(t)}(c);`).join(" ");
  const inputExpr = (n: GraphNode, port: string) => {
    const src = dataIn.get(`${n.id}\u0000${port}`);
    return src ? `V_${safeId(src)}(c, 0)` : String(toInt(n.params[port] ?? param(n, port)));
  };
  const subExpr = (n: GraphNode, port: string) => {
    const src = dataIn.get(`${n.id}\u0000${port}`);
    return src ? `V_${safeId(src)}(c, d + 1)` : String(toInt(n.params[port] ?? param(n, port)));
  };

  const methods: string[] = [];
  for (const n of sorted) {
    const id = safeId(n.id);
    const label = `${n.id} ${CATALOG[n.type].label} by @${n.authorId}`;
    switch (n.type) {
      case "SetVelocity":
      case "AddVelocity": {
        const op = n.type === "SetVelocity" ? ["Fixed.Clamp(vx)", "Fixed.Clamp(vy)", "Fixed.Clamp(vz)"] : ["Fixed.Clamp((long)e.Vx + vx)", "Fixed.Clamp((long)e.Vy + vy)", "Fixed.Clamp((long)e.Vz + vz)"];
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; int vx = ${inputExpr(n, "vx")}; int vy = ${inputExpr(n, "vy")}; int vz = ${inputExpr(n, "vz")}; foreach (var e in S.Select(${cs(String(param(n, "entity")))}, c)) { e.Vx = ${op[0]}; e.Vy = ${op[1]}; e.Vz = ${op[2]}; } ${runOut(n.id, "out")} }`);
        break;
      }
      case "Move": {
        const dir = String(param(n, "direction"));
        const set = dir === "left" ? "e.Vx = Fixed.Clamp(-(long)sp);" : dir === "right" ? "e.Vx = Fixed.Clamp(sp);" : dir === "forward" ? "e.Vz = Fixed.Clamp(-(long)sp);" : dir === "back" ? "e.Vz = Fixed.Clamp(sp);" : dir === "up" ? "e.Vy = Fixed.Clamp(sp);" : dir === "down" ? "e.Vy = Fixed.Clamp(-(long)sp);" : "";
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; int sp = ${inputExpr(n, "speed")}; foreach (var e in S.Select(${cs(String(param(n, "entity")))}, c)) { ${set} } ${runOut(n.id, "out")} }`);
        break;
      }
      case "Stop": {
        const ax = String(param(n, "axis"));
        const parts = [ax === "x" || ax === "ground" || ax === "all" ? "e.Vx = 0;" : "", ax === "z" || ax === "ground" || ax === "all" ? "e.Vz = 0;" : "", ax === "y" || ax === "all" ? "e.Vy = 0;" : ""].join(" ");
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; foreach (var e in S.Select(${cs(String(param(n, "entity")))}, c)) { ${parts} } ${runOut(n.id, "out")} }`);
        break;
      }
      case "Shoot": {
        const dir = String(param(n, "direction"));
        const vec = dir === "facing" ? "dx = e.Fx; dz = e.Fz; if (dx == 0 && dz == 0) dz = -1;" : dir === "forward" ? "dz = -1;" : dir === "back" ? "dz = 1;" : dir === "left" ? "dx = -1;" : dir === "right" ? "dx = 1;" : dir === "up" ? "dy = 1;" : dir === "arc" ? "dx = e.Fx; dz = e.Fz; if (dx == 0 && dz == 0) dz = -1; dy = 1;" : "";
        const aim = dir === "at_player";
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; Prefab d; if (S.TryPrefab(${cs(String(param(n, "prefab")))}, out d)) { int sp = ${inputExpr(n, "speed")}; foreach (var e in S.Select(${cs(String(param(n, "from")))}, c)) { int dx = 0, dy = 0, dz = 0; ${vec} int vx = dx * sp, vy = dy * sp, vz = dz * sp; ${aim ? "S.AimAt(e, sp, out vx, out vz); vy = 0;" : ""} S.QueueSpawnV(${cs(String(param(n, "prefab")))}, e.X + e.W / 2 - d.W / 2, e.Y + e.H / 2 - d.H / 2, e.Z + e.D / 2 - d.D / 2, vx, vy, vz, e.Tag); } } ${runOut(n.id, "out")} }`);
        break;
      }
      case "Spawn":
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; if (!(c.InStart && SuppressStartSpawns)) { int x = ${inputExpr(n, "x")}; int y = ${inputExpr(n, "y")}; int z = ${inputExpr(n, "z")}; S.QueueSpawn(${cs(String(param(n, "prefab")))}, x, y, z); } ${runOut(n.id, "out")} }`);
        break;
      case "Destroy":
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; foreach (var e in S.Select(${cs(String(param(n, "entity")))}, c)) S.QueueDestroy(e); ${runOut(n.id, "out")} }`);
        break;
      case "AddScore":
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; S.AddScore(${inputExpr(n, "n")}); ${runOut(n.id, "out")} }`);
        break;
      case "SetVar":
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; S.Vars[Ns + ${cs("." + String(param(n, "name")))}] = ${inputExpr(n, "value")}; ${runOut(n.id, "out")} }`);
        break;
      case "Win":
      case "Lose":
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; S.End(${cs(n.type === "Win" ? "win" : "lose")}); }`);
        break;
      case "Branch":
        methods.push(`        // ${label}\n        void X_${id}(Ctx c) { if (!Step()) return; if (${inputExpr(n, "cond")} != 0) { ${runOut(n.id, "true")} } else { ${runOut(n.id, "false")} } ${runOut(n.id, "out")} }`);
        break;
      case "Score":
        methods.push(`        int V_${id}(Ctx c, int d) { if (d > 64 || !Step()) return 0; return S.Score; }`);
        methods.push(`        void X_${id}(Ctx c) { if (!Step()) return; }`);
        break;
      case "Const":
        methods.push(`        int V_${id}(Ctx c, int d) { if (d > 64 || !Step()) return 0; return ${toInt(param(n, "value"))}; }`);
        methods.push(`        void X_${id}(Ctx c) { if (!Step()) return; }`);
        break;
      case "GetVar":
        methods.push(`        int V_${id}(Ctx c, int d) { if (d > 64 || !Step()) return 0; int v; return S.Vars.TryGetValue(Ns + ${cs("." + String(param(n, "name")))}, out v) ? v : 0; }`);
        methods.push(`        void X_${id}(Ctx c) { if (!Step()) return; }`);
        break;
      case "Random": {
        const a = toInt(param(n, "min"));
        const b = toInt(param(n, "max"));
        const lo = Math.min(a, b);
        const hi = Math.max(a, b);
        methods.push(`        int V_${id}(Ctx c, int d) { if (d > 64 || !Step()) return 0; return S.Rng.Get(Ns + ${cs(":" + (String(param(n, "stream")) || "main"))}).NextInt(${lo}, ${hi + 1}); }`);
        methods.push(`        void X_${id}(Ctx c) { if (!Step()) return; }`);
        break;
      }
      case "Compare":
        methods.push(`        int V_${id}(Ctx c, int d) { if (d > 64 || !Step()) return 0; int a = ${subExpr(n, "a")}; int b = ${subExpr(n, "b")}; return Cmp(${cs(String(param(n, "op")))}, a, b); }`);
        methods.push(`        void X_${id}(Ctx c) { if (!Step()) return; }`);
        break;
      case "EntityField": {
        const field = String(param(n, "field"));
        const read = field === "count" ? "return sel.Count;" : `if (sel.Count == 0) return 0; var e = sel[0]; ${
          field === "x" ? "return e.X;" : field === "y" ? "return e.Y;" : field === "z" ? "return e.Z;" : field === "vz" ? "return e.Vz;" : field === "vx" ? "return e.Vx;" : field === "vy" ? "return e.Vy;" : field === "grounded" ? "return e.Grounded ? 1 : 0;" : "return 0;"
        }`;
        methods.push(`        int V_${id}(Ctx c, int d) { if (d > 64 || !Step()) return 0; var sel = S.Select(${cs(String(param(n, "entity")))}, c); ${read} }`);
        methods.push(`        void X_${id}(Ctx c) { if (!Step()) return; }`);
        break;
      }
      default:
        // events reached through exec do nothing (matches interpret.ts)
        methods.push(`        void X_${id}(Ctx c) { if (!Step()) return; }`);
    }
  }

  const starts = sorted.filter((n) => n.type === "OnStart").map((n) => `            { var c = new Ctx { InStart = true }; ${runOut(n.id, "out")} }`).join("\n");
  const keys = sorted.filter((n) => n.type === "OnKey").map((n) => {
    const bit = keyBit(String(param(n, "key")));
    if (!bit) return "";
    const when = String(param(n, "when"));
    const cond = when === "held" ? `(mask & ${bit}u) != 0` : when === "released" ? `(released & ${bit}u) != 0` : `(pressed & ${bit}u) != 0`;
    return `            if (${cond}) { var c = new Ctx(); ${runOut(n.id, "out")} }`;
  }).filter(Boolean).join("\n");
  const ticks = sorted.filter((n) => n.type === "OnTick").map((n) => `            if (tick % ${Math.max(1, toInt(param(n, "everyN")))} == 0) { var c = new Ctx(); ${runOut(n.id, "out")} }`).join("\n");
  const collides = sorted.filter((n) => n.type === "OnCollide").map((n) => `            foreach (var pair in S.Pairs(${cs(String(param(n, "tagA")))}, ${cs(String(param(n, "tagB")))})) { var c = new Ctx { A = pair[0], B = pair[1] }; ${runOut(n.id, "out")} }`).join("\n");

  const shares = computeShares(graph);
  return `// ${className}.cs - generated by ForkLab from graph ${hash}
// Title: ${graph.title.replace(/[\r\n]/g, " ")}
// Authors: ${shares.map((s) => `@${s.handle} ${(s.bps / 100).toFixed(2)}%`).join(", ")}
// License: ${graph.license.type === "free" ? "free to fork" : `paid, ${graph.license.priceLamports} lamports (devnet)`}
// Do not edit by hand: re-export from ForkLab so the graph hash stays meaningful.
using System;
using System.Collections.Generic;

namespace ForkLab
{
    public sealed class ${className} : GraphProgram
    {
        public const string GraphHash = ${cs(hash)};
        public ${className}(string ns = ${cs(ns)}, bool suppressStartSpawns = false) { Ns = ns; SuppressStartSpawns = suppressStartSpawns; }

        public override void RunStart()
        {
${starts}
        }

        public override void RunKeys(uint mask, uint pressed, uint released)
        {
${keys}
        }

        public override void RunTicks(int tick)
        {
${ticks}
        }

        public override void RunCollisions()
        {
${collides}
        }

${methods.join("\n")}
    }
}
`;
}

export function behaviourSource(className: string, seed = 1): string {
  return `// MechanicBehaviour.cs - generated by ForkLab. Drop on an empty GameObject.
using System.Collections.Generic;
using UnityEngine;
using ForkLab;

public class MechanicBehaviour : MonoBehaviour
{
    public uint seed = ${seed};
    public float unitsPerWorldUnit = 1f;
    private Sim sim;
    private readonly Dictionary<int, Transform> views = new Dictionary<int, Transform>();
    private static readonly KeyCode[] Keys = { KeyCode.Space, KeyCode.LeftArrow, KeyCode.RightArrow, KeyCode.UpArrow, KeyCode.DownArrow, KeyCode.A, KeyCode.D, KeyCode.W, KeyCode.S };
    private uint heldMask;

    void Start()
    {
        Time.fixedDeltaTime = 1f / 60f;
        sim = new Sim(seed, new ${className}());
    }

    void Update()
    {
        uint m = 0;
        for (int i = 0; i < Keys.Length; i++) if (Input.GetKey(Keys[i])) m |= 1u << i;
        heldMask = m;
    }

    void FixedUpdate()
    {
        if (sim == null) return;
        sim.StepTick(heldMask);
        var seen = new HashSet<int>();
        foreach (var e in sim.Entities)
        {
            seen.Add(e.Id);
            Transform t;
            if (!views.TryGetValue(e.Id, out t))
            {
                var go = GameObject.CreatePrimitive(PrimitiveType.Cube);
                go.name = e.Tag + "_" + e.Id;
                t = go.transform;
                t.SetParent(transform, false);
                views[e.Id] = t;
            }
            float s = unitsPerWorldUnit / 1000f;
            t.localScale = new Vector3(e.W * s, e.H * s, e.D * s);
            t.localPosition = new Vector3((e.X + e.W / 2f) * s, (e.Y + e.H / 2f) * s, -(e.Z + e.D / 2f) * s);
        }
        var gone = new List<int>();
        foreach (var kv in views) if (!seen.Contains(kv.Key)) gone.Add(kv.Key);
        foreach (var id in gone) { Destroy(views[id].gameObject); views.Remove(id); }
        if (sim.Status != "running") enabled = false;
    }
}
`;
}

export function exportCSharpFiles(graph: Graph, hash: string, prefabs: Record<string, PrefabDef> = {}): Record<string, string> {
  const className = `Mechanic_${slugify(graph.title)}`;
  return {
    "ForkLabCore.cs": coreSource({ ...(graph.prefabs ?? {}), ...prefabs }),
    [`${className}.cs`]: mechanicSource(graph, hash, className),
    "MechanicBehaviour.cs": behaviourSource(className),
  };
}
