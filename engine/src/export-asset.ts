import { slugify } from "./export-csharp";
import { assetSchema, type Asset } from "./asset";

/*
 * Asset export for Unity: ScriptableObject classes, the asset JSON, and an editor importer that reads the JSON,
 * creates the ScriptableObject, and for a prefab builds a primitive and saves it with PrefabUtility.SaveAsPrefabAsset.
 * The importer has not been run against Unity in this environment; test it in a clean project.
 */

export const ASSETS_CS = `// ForkLabAssets.cs - generated by ForkLab.
using UnityEngine;

namespace ForkLab
{
    [CreateAssetMenu(menuName = "ForkLab/Prefab asset")]
    public class ForkLabPrefabAsset : ScriptableObject
    {
        public string assetHash;
        public string title;
        public string author;
        public string entityTag;
        public int widthMilli, heightMilli, vxMilliPerTick, vyMilliPerTick;
        public Color color = Color.white;
    }

    [CreateAssetMenu(menuName = "ForkLab/Theme asset")]
    public class ForkLabThemeAsset : ScriptableObject
    {
        public string assetHash;
        public string title;
        public string author;
        public Color sky = Color.white, ground = Color.gray, accent = Color.blue;
    }
}
`;

export const IMPORTER_CS = `// Editor/ForkLabAssetImporter.cs - generated by ForkLab. Adds Tools > ForkLab > Import asset JSON.
#if UNITY_EDITOR
using System.IO;
using UnityEditor;
using UnityEngine;

namespace ForkLab.Editor
{
    public static class ForkLabAssetImporter
    {
        [System.Serializable] class PrefabJson { public string tag; public int w, h, vx, vy; public string color; }
        [System.Serializable] class ThemeJson { public string sky, ground, accent; }
        [System.Serializable] class AssetJson { public string schema, kind, title, authorId; public PrefabJson prefab; public ThemeJson theme; }
        [System.Serializable] class Envelope { public string hash; public AssetJson asset; }

        static Color Hex(string s) { Color c; return ColorUtility.TryParseHtmlString(s, out c) ? c : Color.white; }

        [MenuItem("Tools/ForkLab/Import asset JSON")]
        public static void Import()
        {
            var path = EditorUtility.OpenFilePanel("ForkLab asset JSON", "", "json");
            if (string.IsNullOrEmpty(path)) return;
            var env = JsonUtility.FromJson<Envelope>(File.ReadAllText(path));
            if (env == null || env.asset == null || env.asset.schema != "forklab.asset.v1") { Debug.LogError("Not a forklab.asset.v1 file."); return; }
            Directory.CreateDirectory("Assets/ForkLab");
            var a = env.asset;
            var safe = string.Join("_", a.title.Split(Path.GetInvalidFileNameChars()));
            if (a.kind == "prefab" && a.prefab != null)
            {
                var so = ScriptableObject.CreateInstance<ForkLabPrefabAsset>();
                so.assetHash = env.hash; so.title = a.title; so.author = a.authorId; so.entityTag = a.prefab.tag;
                so.widthMilli = a.prefab.w; so.heightMilli = a.prefab.h; so.vxMilliPerTick = a.prefab.vx; so.vyMilliPerTick = a.prefab.vy; so.color = Hex(a.prefab.color);
                AssetDatabase.CreateAsset(so, "Assets/ForkLab/" + safe + ".asset");
                var go = GameObject.CreatePrimitive(PrimitiveType.Cube);
                go.name = a.title;
                go.transform.localScale = new Vector3(a.prefab.w / 1000f, a.prefab.h / 1000f, 1f);
                var mat = new Material(Shader.Find("Standard")) { color = so.color };
                AssetDatabase.CreateAsset(mat, "Assets/ForkLab/" + safe + "_mat.mat");
                go.GetComponent<Renderer>().sharedMaterial = mat;
                try { go.tag = a.prefab.tag; } catch { Debug.LogWarning("Add the tag '" + a.prefab.tag + "' in Tags and Layers to tag the prefab."); }
                PrefabUtility.SaveAsPrefabAsset(go, "Assets/ForkLab/" + safe + ".prefab");
                Object.DestroyImmediate(go);
            }
            else if (a.kind == "theme" && a.theme != null)
            {
                var so = ScriptableObject.CreateInstance<ForkLabThemeAsset>();
                so.assetHash = env.hash; so.title = a.title; so.author = a.authorId;
                so.sky = Hex(a.theme.sky); so.ground = Hex(a.theme.ground); so.accent = Hex(a.theme.accent);
                AssetDatabase.CreateAsset(so, "Assets/ForkLab/" + safe + ".asset");
            }
            AssetDatabase.SaveAssets();
            Debug.Log("Imported ForkLab asset " + a.title + " (" + env.hash + ")");
        }
    }
}
#endif
`;

export function exportAssetFiles(asset: Asset, hash: string): Record<string, string> {
  const slug = slugify(asset.title);
  return {
    "ForkLabAssets.cs": ASSETS_CS,
    [`${slug}.asset.json`]: JSON.stringify({ hash, asset }, null, 2),
    "Editor/ForkLabAssetImporter.cs": IMPORTER_CS,
  };
}

/** Parse the exported JSON back. Used to prove the file round-trips the schema. */
export function parseExportedAsset(json: string): { hash: string; asset: Asset } {
  const raw = JSON.parse(json) as { hash: string; asset: unknown };
  return { hash: raw.hash, asset: assetSchema.parse(raw.asset) };
}
